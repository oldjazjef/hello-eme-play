/// <reference types="node" />
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { PLAY_SCHEMA } from './schema.js';
import { buildReference, referenceMarkdown } from './reference.js';

describe('buildReference', () => {
	it('has a section for every top-level setting, in order', () => {
		expect(buildReference().sections.map((section) => section.id)).toEqual(
			Object.keys(PLAY_SCHEMA.fields)
		);
	});

	it('lists nested settings of maps and lists', () => {
		const paths = buildReference().sections.flatMap((section) =>
			section.rows.map((row) => row.path)
		);
		expect(paths).toContain('entities.<id>.stats.<id>');
		expect(paths).toContain('spawns[].every');
		expect(paths).toContain('keys.left');
		expect(paths).toContain('triggers[].conditions');
	});

	it('documents every event, action, condition and default key', () => {
		const reference = buildReference();
		expect(reference.events.map((event) => event.id)).toContain('viewChange');
		expect(reference.actions.map((action) => action.id)).toEqual(
			expect.arrayContaining(['spawn', 'setView', 'win', 'lose'])
		);
		expect(reference.conditions.map((condition) => condition.id)).toContain('kills');
		const keys = Object.fromEntries(reference.keys.map((key) => [key.path, key.keys]));
		expect(keys['keys.jump']).toEqual(['KeyE']);
		expect(keys['moves.punch.keys']).toEqual(['Space']);
	});

	it('gives numbers their bounds and defaults', () => {
		const row = buildReference()
			.sections.flatMap((section) => section.rows)
			.find((candidate) => candidate.path === 'game.lives');
		expect(row).toMatchObject({ type: 'whole number', default: '1', limits: '1–99' });
	});
});

describe('referenceMarkdown', () => {
	it('is written in the asked language', () => {
		expect(referenceMarkdown('en')).toContain('# Configuration reference');
		expect(referenceMarkdown('de')).toContain('# Konfigurations-Referenz');
		expect(referenceMarkdown('de')).toContain('Leben (Versuche)');
	});

	it('has no table row that breaks on a pipe', () => {
		for (const line of referenceMarkdown('en')
			.split('\n')
			.filter((l) => l.startsWith('| `'))) {
			// Unescaped pipes: 5 columns means 6 separators in the settings tables.
			const separators = line.replaceAll('\\|', '').split('|').length - 1;
			expect(separators === 6 || separators === 3 || separators === 2, line).toBe(true);
		}
	});

	// The files are generated by `npm run docs`; this keeps them from going stale.
	it.each([
		['en', 'REFERENCE.md'],
		['de', 'REFERENCE.de.md']
	] as const)('matches docs/%s', (lang, file) => {
		const written = readFileSync(new URL(`../../../docs/${file}`, import.meta.url), 'utf8');
		const normalise = (text: string) =>
			text
				.replace(/[ \t|:-]+/g, ' ')
				.replace(/\s+/g, ' ')
				.trim();
		expect(normalise(written), `run "npm run docs": docs/${file} is stale`).toBe(
			normalise(referenceMarkdown(lang))
		);
	});
});
